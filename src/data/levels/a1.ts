import type { Exercise, Lang, Lesson, Unit, VocabItem } from '@/domain/types'

// Contenido del nivel A1 — 4 unidades × 3 lecciones.
// Helpers locales para mantener el archivo legible. Los ids (e1..eN) se asignan en `lesson()`.

type V = VocabItem[]

const ct = (prompt: string, promptLang: Lang, options: string[], correct: number, explanation: string, vocab?: V): Exercise => ({
  id: '', type: 'choose-translation', prompt, promptLang, options, correct, explanation, vocab,
})
const bs = (prompt: string, promptLang: Lang, accepted: string[], bank: string[], explanation: string, vocab?: V): Exercise => ({
  id: '', type: 'build-sentence', prompt, promptLang, accepted, bank, explanation, vocab,
})
const tt = (prompt: string, promptLang: Lang, accepted: string[], explanation: string, vocab?: V): Exercise => ({
  id: '', type: 'type-translation', prompt, promptLang, accepted, explanation, vocab,
})
const mp = (pairs: { en: string; es: string }[], explanation: string, emojis: string[] = []): Exercise => ({
  id: '', type: 'match-pairs', pairs, explanation,
  vocab: pairs.map((p, i) => (emojis[i] ? { en: p.en, es: p.es, emoji: emojis[i] } : { en: p.en, es: p.es })),
})
const lt = (audio: string, accepted: string[], translation: string, explanation: string, vocab?: V): Exercise => ({
  id: '', type: 'listen-type', audio, accepted, translation, explanation, vocab,
})
const lc = (audio: string, options: string[], correct: number, explanation: string, vocab?: V): Exercise => ({
  id: '', type: 'listen-choose', audio, options, correct, explanation, vocab,
})
const fb = (sentence: string, options: string[], correct: number, translation: string, explanation: string, vocab?: V): Exercise => ({
  id: '', type: 'fill-blank', sentence, options, correct, translation, explanation, vocab,
})
const ci = (word: string, options: [string, string][], correct: number, explanation: string, vocab?: V): Exercise => ({
  id: '', type: 'choose-image', word, options: options.map(([emoji, label]) => ({ emoji, label })), correct, explanation, vocab,
})
const sp = (phrase: string, translation: string, explanation: string, vocab?: V): Exercise => ({
  id: '', type: 'speak', phrase, translation, explanation, vocab,
})

const lesson = (id: string, title: string, exs: Exercise[]): Lesson => ({
  id,
  title,
  exercises: exs.map((e, i) => ({ ...e, id: `e${i + 1}` }) as Exercise),
})

